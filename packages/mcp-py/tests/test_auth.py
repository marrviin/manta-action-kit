"""Handshake auth — golden vectors + behavior tests.

The golden vectors below were generated by running the REAL TS twin
(packages/mcp/src/auth.ts, node:crypto) under node's native type stripping:

    node --input-type=module -e "
      import { welcomeProof, authProof } from './packages/mcp/src/auth.ts';
      for (const [token, nonce] of VECTORS)
        console.log(JSON.stringify({ token, nonce,
          welcome: welcomeProof(token, nonce), auth: authProof(token, nonce) }));
    "

If any of these fail, the Python side has drifted from the wire contract and
neither the extension nor the Node server will complete a handshake with it.
"""

import pytest

from manta_action_kit_mcp.auth import (
    auth_proof,
    new_nonce,
    verify_auth_proof,
    verify_welcome_proof,
    welcome_proof,
)

GOLDEN_VECTORS = [
    (
        "secret-token",
        "hello-nonce-1",
        "e7b9ab42247699e9af20ce7d3cdf343401bf9427c97b7510043635dc5c56e6c6",
        "f69b21dcf24b1865dd4552d26f0f54d06c53b042cb787b2f0b0bfa5021cc8a0a",
    ),
    (
        "a-very-long-token-with-unicode-密",
        "server-nonce-2",
        "89b0a1c2af2e0d108007fe27a3549867f1e7a3195ca4be4edd3a9eb8b56e022e",
        "b20a4c8cb58607db521f13dc19f9e38f77a75bf79f8bc7193316b5334a903b5e",
    ),
    (
        "",
        "empty-token-msg",
        "ca319df22180cc0fd016844d50624b3e7b26479f01dc2f0fc394294c45c773b2",
        "f45e2ff48488c1fe6ff4296456be82bf523af9a08ef6741658478e056672e7a4",
    ),
]


@pytest.mark.parametrize("token,nonce,welcome,auth", GOLDEN_VECTORS)
def test_golden_vectors_match_ts_implementation(token, nonce, welcome, auth):
    """byte-identical with the node:crypto twins (see module docstring)."""
    assert welcome_proof(token, nonce) == welcome
    assert auth_proof(token, nonce) == auth


@pytest.mark.parametrize("token,nonce,welcome,auth", GOLDEN_VECTORS)
def test_verify_accepts_valid_proofs(token, nonce, welcome, auth):
    assert verify_auth_proof(token, nonce, auth)
    assert verify_welcome_proof(token, nonce, welcome)


def test_verify_rejects_wrong_token():
    assert not verify_auth_proof("wrong", "nonce", auth_proof("right", "nonce"))
    assert not verify_welcome_proof("wrong", "nonce", welcome_proof("right", "nonce"))


def test_verify_rejects_wrong_nonce():
    assert not verify_auth_proof("token", "nonce-1", auth_proof("token", "nonce-2"))


@pytest.mark.parametrize(
    "proof",
    [
        "",  # empty
        "zz",  # non-hex
        "abc",  # odd length
        "00" * 32,  # right length, wrong content
        "e7b9ab42247699e9af20ce7d3cdf343401bf9427c97b7510043635dc5c56e6c",  # truncated
    ],
)
def test_malformed_proofs_fail(proof):
    assert not verify_auth_proof("token", "nonce", proof)


def test_hex_is_case_insensitive():
    """Node's Buffer.from(proof, 'hex') accepts mixed case — match it."""
    token, nonce = "token", "nonce"
    assert verify_auth_proof(token, nonce, auth_proof(token, nonce).upper())


def test_new_nonce_is_fresh_string():
    a, b = new_nonce(), new_nonce()
    assert a != b
    assert isinstance(a, str) and len(a) > 0
